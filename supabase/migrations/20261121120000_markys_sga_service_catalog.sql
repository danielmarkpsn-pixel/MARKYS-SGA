create table if not exists public.markys_service_catalog (
 id uuid primary key default gen_random_uuid(),
 exam_name text not null check(length(trim(exam_name)) between 1 and 160),
 room_name text not null check(length(trim(room_name)) between 1 and 80),
 attendance_name text not null check(length(trim(attendance_name)) between 1 and 120),
 active boolean not null default true,
 created_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create unique index if not exists markys_service_catalog_room_exam_uidx on public.markys_service_catalog(lower(room_name),lower(exam_name));
create index if not exists markys_service_catalog_active_room_idx on public.markys_service_catalog(active,room_name);
alter table public.markys_service_catalog enable row level security;
drop policy if exists markys_service_catalog_read_staff on public.markys_service_catalog;
create policy markys_service_catalog_read_staff on public.markys_service_catalog for select to authenticated using(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role in ('master','financeiro','recepcao','profissional')));
drop policy if exists markys_service_catalog_insert_finance on public.markys_service_catalog;
create policy markys_service_catalog_insert_finance on public.markys_service_catalog for insert to authenticated with check(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role in ('master','financeiro')));
drop policy if exists markys_service_catalog_update_finance on public.markys_service_catalog;
create policy markys_service_catalog_update_finance on public.markys_service_catalog for update to authenticated using(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role in ('master','financeiro'))) with check(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role in ('master','financeiro')));
drop policy if exists markys_service_catalog_delete_finance on public.markys_service_catalog;
create policy markys_service_catalog_delete_finance on public.markys_service_catalog for delete to authenticated using(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.active and p.role in ('master','financeiro')));
